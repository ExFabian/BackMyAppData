                caption = "Fetching directories failed";
                message = $"Fetching directories failed: {exceptionMessage}";
                break;
        }

        DialogResult res = MessageBox.Show(message, caption, buttons, icon);
        return res;
    }

    public static bool SafeDeleteTempFolder(bool force = false)
    {
        try
        {
            if (!Directory.Exists(Global.TempPath)) return true;

            if (Directory.GetDirectories(Global.TempPath).Count() == 0) return true;

            if (!force)
            {
                // Only recursively delete the temp folder if and only if an AppData folder is present
                string[] foldersToCheck = { "Local", "Roaming", "LocalLow" };
                foreach (String dir in Directory.GetDirectories(Global.TempPath))
                {
                    String newDir = Path.GetFileName(dir);

                    if (foldersToCheck.Contains(newDir)) continue;
                    if (Directory.GetDirectories(dir).Count() == 0) continue;

                    throw new UnauthorizedAccessException($"The temp folder contains an unknown file/folder: {dir}");
                }
            }

            Directory.Delete(Global.TempPath, true);
            return true;
        }
        catch (UnauthorizedAccessException)
        {
            DialogResult res = Utils.ShowErrorMsg(ErrorCode.MiscTempDeletionUnsafe);
            if (res == DialogResult.Yes)
                return SafeDeleteTempFolder(true);
            else
                return false;
        }
        catch (Exception ex)
        {
            Utils.ShowErrorMsg(ErrorCode.MiscTempDeletionFailed, ex.Message);
            return false;
        }
    }

    public static void CopyFile(String sourceDir, String destinationDir)
    {
        var file = new FileInfo(sourceDir);

        if (file.Attributes.HasFlag(FileAttributes.Hidden))
            return;

        String targetFilePath = Path.Combine(destinationDir, file.Name);
        file.CopyTo(destinationDir, true);
    }

    public static bool CopyDirectory(String sourceDir, String destinationDir, bool recursive, bool autoSkipFilesInUse = false ,bool verifyCheckState = false, bool inSubfolder = false)
    {
        // Get information about the source directory
        var dir = new DirectoryInfo(sourceDir);

        // Check if the source directory exists
        if (!dir.Exists)
        {
            if(!inSubfolder)
                ShowErrorMsg(ErrorCode.BackupFolderNotFound);
            else
                ShowErrorMsg(ErrorCode.BackupSubFolderNotFound);
            return true;
        }
        if (dir.Attributes.HasFlag(FileAttributes.Hidden))
        {
            // log "skipping hidden folder"
            return true;
        }

        // Cache directories before we start copying
        DirectoryInfo[] dirs = dir.GetDirectories();

        // Create the destination directory
        Directory.CreateDirectory(destinationDir);

        // Get the files in the source directory and copy to the destination directory
        foreach (FileInfo file in dir.GetFiles())
        {
            if (!inSubfolder)
            {
                if (Global.checkedList.Where(e => e.Name == file.DirectoryName)
                        .Any(e => e.SubItem
                        .Any(sub => sub.Name == file.Name && sub.State == CheckState.Unchecked))
                    )
                    continue;
            }
            if (file.Attributes.HasFlag(FileAttributes.Hidden)) // todo: toggleable option
                continue;

            bool retry;
            do
            {
                retry = false;

                try
                {
                    CopyFile(Path.Combine(sourceDir, file.Name), Path.Combine(destinationDir, file.Name));
                }
                catch (IOException ex)
                {
                    if (!autoSkipFilesInUse)
                    {
                        String caption = "Copy error";
                        String message = $"The file {file.FullName} could not be copied, most likely because it's being used by another process. Try closing any programs that may be using the file.\n" +
                                         $"Details: {ex.Message}\n" +
                                         "Abort to cancel the backup/restore process, Retry to try copying the file again or Ignore to skip this file.";
                        MessageBoxButtons buttons = MessageBoxButtons.AbortRetryIgnore;
                        MessageBoxIcon icon = MessageBoxIcon.Error;
                        DialogResult res = MessageBox.Show(message, caption, buttons, icon);

                        switch (res)
                        {
                            case DialogResult.Abort:
                                return false;

                            case DialogResult.Retry:
                                retry = true;
                                break;

                            case DialogResult.Ignore:
                                break;
                        }
                    }
                }
            } while (retry);
        }

        // If recursive and copying subdirectories, recursively call this method
        if (recursive)
        {
            foreach (DirectoryInfo subDir in dirs)
            {
                if (!inSubfolder && verifyCheckState)
                {
                    if (Global.checkedList.Where(e => e.Name == subDir.Parent!.FullName)
                        .Any(e => e.SubItem
                        .Any(sub => sub.Name == subDir.Name && sub.State == CheckState.Unchecked))
                    )
                        continue;
                }

                string newDestinationDir = Path.Combine(destinationDir, subDir.Name);
                bool success = CopyDirectory(subDir.FullName, newDestinationDir, true, autoSkipFilesInUse, verifyCheckState, true);
                if (!success) return false;
            }
        }

        return true;
    }

