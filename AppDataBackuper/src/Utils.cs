    {
        // Get information about the source directory
        var dir = new DirectoryInfo(sourceDir);

        // Check if the source directory exists
        if (!dir.Exists)
        {
            if (!inSubfolder)
                ShowErrorMsg(ErrorCode.BackupFolderNotFound);
            else
                ShowErrorMsg(ErrorCode.BackupSubFolderNotFound);
            return true;
        }
