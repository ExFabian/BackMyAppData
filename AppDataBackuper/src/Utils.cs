                                         "Abort to cancel the backup/restore process, Retry to try copying the file again or Ignore to skip this file.";
                        MessageBoxButtons buttons = MessageBoxButtons.AbortRetryIgnore;
                        MessageBoxIcon icon = MessageBoxIcon.Error;
                        DialogResult res = MessageBox.Show(message, caption, buttons, icon);

                        switch (res)
                        {
                            case DialogResult.Abort:
                                worker.ReportProgress(-1, "Aborting");
                                return false;

                            case DialogResult.Retry:
                                retry = true;
                                break;

                            case DialogResult.Ignore:
                                worker.ReportProgress(-1, $"Skipped file {file.Name}");
                                break;
                        }
                    }
                    
                }
            } while (retry);
        }

        // If recursive and copying subdirectories, recursively call this method
        if (recursive)
        {
            foreach (DirectoryInfo subDir in dirs)
            {
                if (!inSubfolder && verifyCheckState)
