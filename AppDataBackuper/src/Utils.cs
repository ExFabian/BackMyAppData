    public static DialogResult ShowErrorMsg(ErrorCode code, String exceptionMessage = "")
    {
        String caption = "";
        String message = "";
        MessageBoxButtons buttons = MessageBoxButtons.OK;
        MessageBoxIcon icon = MessageBoxIcon.Error;

        switch (code)
        {
            case ErrorCode.OK:
                caption = "Success";
                message = "The operation succeeded :)";
                icon = MessageBoxIcon.Information;
                break;

            case ErrorCode.MiscException:
                caption = "Error";
                message = $"Something failed: {exceptionMessage}";
                break;

            case ErrorCode.MiscDirectoryNotFound:
                caption = "Error";
                message = $"The selected item ({exceptionMessage}) was not found, maybe it was deleted?";
                break;

            case ErrorCode.MiscInvalidAppData:
                caption = "Error";
                message = "An invalid AppData type was selected. This is very weird and shouldn't happen. Please report this bug.";
                break;

            case ErrorCode.MiscTempDeletionFailed:
                caption = "Error";
                message = $"The temp folder could not be deleted. Manually deleting the \"temp\" folder located in the executable's directory may fix this. Please report this bug.\nException details: {exceptionMessage}";
                break;

            case ErrorCode.MiscTempDeletionUnsafe:
                caption = "Error";
                message = "The temp folder contains unknown files/folders, likely not generated by the program. Deleting the temp folder in this state could be dangerous!\nSelect \"Yes\" if you want to delete the folder anyways, otherwise select \"No\".";
                buttons = MessageBoxButtons.YesNo;
                break;

            case ErrorCode.BackupException:
                caption = "Backup failed";
                message = $"Backup failed: {exceptionMessage}";
                break;

            case ErrorCode.BackupEmptyFileName:
                caption = "Backup failed";
                message = "The file name cannot be empty.";
                break;

            case ErrorCode.BackupFolderNotFound:
                caption = "Backup failed";
                message = "One of the selected folders was not found, maybe it was deleted?";
                break;

            case ErrorCode.BackupSubFolderNotFound:
                caption = "Backup failed";
                message = "One of the subfolders inside a selected folder was not found, maybe it was deleted?";
                break;

            case ErrorCode.BackupNoCheckedItems:
                caption = "Backup failed";
                message = "No folder has been selected for backup yet.";
                break;

            case ErrorCode.BackupCancelled:
                caption = "Backup cancelled";
                message = "The backup operation has been cancelled, no backup file was created.";
                icon = MessageBoxIcon.Information;
                break;

            case ErrorCode.RestoreException:
                caption = "Restore failed";
                message = $"Restore failed: {exceptionMessage}";
                break;

            case ErrorCode.RestoreEmptyFileName:
                caption = "Restore failed";
                message = "No file has been selected.";
                break;

            case ErrorCode.RestoreInvalidFile:
                caption = "Restore failed";
                message = "The selected file is not a valid backup file.";
