                retry = false;

                try
                {
                    worker.ReportProgress(-1, $"Copying file {file.Name} to {destinationDir}");

                    CopyFile(Path.Combine(sourceDir, file.Name), Path.Combine(destinationDir, file.Name));
                }
                catch (IOException ex)
                {
                    if (autoSkipFilesInUse)
                    {
                        worker.ReportProgress(-1, $"Skipped file {file.Name}");
                    }
                    else
                    {
                        String caption = "Copy error";
